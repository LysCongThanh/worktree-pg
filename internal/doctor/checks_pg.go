package doctor

import (
	"context"
	"fmt"

	"github.com/jackc/pgx/v5"
)

// adminCaps is what the admin role can do (spec §5 "Clone": admin caps).
type adminCaps struct {
	versionNum                  int
	user                        string
	super, createDB, createRole bool
}

// checkAdmin resolves the admin DSN (external clusters), connects with a short
// timeout and checks the privileges `up` needs. Managed docker clusters create
// their own superuser, so only DSN-based clusters are probed here.
func (r *run) checkAdmin(ctx context.Context) {
	if r.cfg == nil {
		r.add("admin connection", Skip, "no valid config", "")
		return
	}
	if r.cfg.Cluster.Source == "docker" {
		r.add("admin connection", Skip, "managed docker cluster (credentials generated by worktree-pg)", "")
		return
	}
	dsn, err := r.cfg.ResolveAdminDSN(r.o.Getenv)
	if err != nil {
		r.add("admin dsn", Fail, err.Error(), hintOf(err))
		return
	}
	r.add("admin dsn", OK, "from "+dsnSource(r.cfg.Cluster.AdminDSNEnv, r.o.Getenv), "")
	cctx, cancel := context.WithTimeout(ctx, r.o.Timeout)
	defer cancel()
	conn, err := pgx.Connect(cctx, dsn)
	if err != nil {
		// pgx errors can echo the DSN host/user but never the password
		r.add("admin connection", Fail, "cannot connect: "+err.Error(), "check the server is running and the DSN is correct")
		return
	}
	defer conn.Close(context.WithoutCancel(ctx))
	var c adminCaps
	err = conn.QueryRow(cctx, `SELECT current_setting('server_version_num')::int, current_user,
		rolsuper, rolcreatedb, rolcreaterole FROM pg_roles WHERE rolname = current_user`).
		Scan(&c.versionNum, &c.user, &c.super, &c.createDB, &c.createRole)
	if err != nil {
		r.add("admin connection", Fail, "capability query failed: "+err.Error(), "")
		return
	}
	r.add("admin connection", OK, fmt.Sprintf("PostgreSQL %d as %s", c.versionNum/10000, c.user), "")
	r.checkCaps(c)
	r.checkExtensions(cctx, conn, c)
}

// checkCaps applies the CREATEDB / CREATEROLE rules and the supported-version range.
func (r *run) checkCaps(c adminCaps) {
	if major := c.versionNum / 10000; major < 15 {
		r.add("server version", Warn, fmt.Sprintf("PostgreSQL %d is older than the tested 15-18", major), "")
	}
	switch {
	case c.super:
		r.add("privileges", OK, "superuser", "")
	case !c.createDB:
		r.add("privileges", Fail, c.user+" lacks CREATEDB", "ALTER ROLE "+c.user+" CREATEDB")
	case r.cfg.Database.Roles == "per_worktree" && !c.createRole:
		r.add("privileges", Fail, c.user+" lacks CREATEROLE (needed for roles = \"per_worktree\")",
			"ALTER ROLE "+c.user+" CREATEROLE, or set [database] roles = \"shared\"")
	default:
		r.add("privileges", OK, "CREATEDB, CREATEROLE (non-superuser)", "")
	}
}

// checkExtensions verifies each configured extension is installed on the server
// and warns about untrusted ones under a non-superuser admin (spike D7).
func (r *run) checkExtensions(ctx context.Context, conn *pgx.Conn, c adminCaps) {
	for _, ext := range r.cfg.Template.Extensions {
		var n int
		var trusted bool
		err := conn.QueryRow(ctx, `SELECT count(*), coalesce(bool_or(trusted), false)
			FROM pg_available_extension_versions WHERE name = $1`, ext).Scan(&n, &trusted)
		name := "extension " + ext
		switch {
		case err != nil:
			r.add(name, Fail, err.Error(), "")
		case n == 0:
			r.add(name, Fail, "not available on the server", "install the extension package on the PostgreSQL host")
		case !trusted && !c.super:
			r.add(name, Warn, "untrusted: CREATE EXTENSION needs a superuser admin",
				"use a superuser admin DSN or pre-create it in template1")
		default:
			r.add(name, OK, "available", "")
		}
	}
}

// dsnSource names where the DSN came from without revealing it.
func dsnSource(env string, getenv func(string) string) string {
	if env != "" && getenv(env) != "" {
		return "$" + env
	}
	return "admin_dsn_file"
}
